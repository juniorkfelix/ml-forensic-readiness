"""Generate a SYNTHETIC results set to build and demonstrate the analysis pipeline.

!!! SYNTHETIC DATA - NOT EXPERIMENTAL RESULTS !!!
Values are drawn from distributions centred on the *predictions* in
docs/pilot_expected_outcomes.md (researcher decision D-056, time constraint). They
exist to exercise Phases 19-20 (statistics, tables, figures). They must never be
reported as measurements. Every row carries data_origin=SYNTHETIC and outputs go
only to results/synthetic/.

Usage:
    python scripts/generate_synthetic_results.py [--seeds 5] [--rng 20260928]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUT = PROJECT_ROOT / "results" / "synthetic"

# (mean, sd) per pipeline; centred on docs/pilot_expected_outcomes.md predictions
EC = {"A": (0.42, 0.04), "B": (0.63, 0.04), "C": (0.97, 0.02)}
ERR = {"A": (0.68, 0.05), "B": (0.92, 0.04), "C": (0.99, 0.02)}
RCI = {"A": 0.75, "B": 0.75, "C": 1.0}
RECON_S = {"A": (0.4, 0.1), "B": (1.8, 0.4), "C": (3.9, 0.8)}
EVID_MB = {"A": (0.05, 0.005), "B": (47.0, 0.6), "C": (61.0, 0.8)}
TRAIN_OVH = {"A": 0.0, "B": 0.02, "C": 0.035}


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--seeds", type=int, default=5)
    p.add_argument("--rng", type=int, default=20260928)
    args = p.parse_args()
    rng = np.random.default_rng(args.rng)
    rows = []
    cells = [("none", 0.0)] + [
        (a, r) for a in ("label_flip", "backdoor") for r in (0.01, 0.03, 0.05)
    ]
    for seed in range(1, args.seeds + 1):
        base_train = rng.normal(694, 8)  # shared by the A/B/C triple of a seed (paired design)
        for attack, rate in cells:
            ca = rng.normal(0.933, 0.003) - (0.6 * rate if attack == "label_flip" else 0.02 * rate)
            asr = min(1.0, rng.normal(0.9 + 2 * rate, 0.02)) if attack == "backdoor" else np.nan
            s2t = rng.normal(8 * rate, 0.03) if attack == "label_flip" else np.nan
            for pl in "ABC":
                clip = lambda v: float(np.clip(v, 0, 1))  # noqa: E731
                rows.append(
                    {
                        "data_origin": "SYNTHETIC",
                        "experiment_id": f"SYN-{ {'none': 'CLEAN', 'label_flip': 'LF', 'backdoor': 'BD'}[attack]}"
                        f"-{pl}-{int(round(rate * 100)):02d}-S{seed:03d}",
                        "pipeline": pl,
                        "attack_type": attack,
                        "poison_rate": rate,
                        "seed": seed,
                        "clean_test_accuracy": clip(ca + rng.normal(0, 0.0005)),
                        "attack_success_rate": asr,
                        "source_to_target_rate": s2t,
                        "evidence_completeness": clip(rng.normal(*EC[pl])),
                        "event_recovery_rate": clip(rng.normal(*ERR[pl])),
                        "timeline_kendall_tau_b": clip(rng.normal(0.98, 0.02)),
                        "rci_score": RCI[pl] if attack != "none" else np.nan,
                        "clean_control_correct": (pl != "A") if attack == "none" else np.nan,
                        "reconstruction_seconds": max(0.05, rng.normal(*RECON_S[pl])),
                        "training_seconds": base_train * (1 + TRAIN_OVH[pl] + rng.normal(0, 0.004)),
                        "evidence_total_bytes": max(1e4, rng.normal(*EVID_MB[pl]) * 1024**2),
                        "peak_rss_mb": rng.normal(1720 + (60 if pl != "A" else 0), 15),
                    }
                )
    OUT.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "run_index_SYNTHETIC.csv", index=False)
    (OUT / "README.md").write_text(
        "# SYNTHETIC DATA - NOT EXPERIMENTAL RESULTS\n\n"
        "Everything in this folder was generated by `scripts/generate_synthetic_results.py` "
        f"(rng seed {args.rng}) from distributions centred on the predictions in "
        "`docs/pilot_expected_outcomes.md` (decision D-056). It demonstrates the analysis "
        "pipeline only. **Do not report any value here as a measurement.** Real results are "
        "produced by `scripts/run_pilot.py` / the final matrix and analysed with the same "
        "scripts.\n",
        encoding="utf-8",
    )
    print(
        f"SYNTHETIC: {len(df)} rows -> {(OUT / 'run_index_SYNTHETIC.csv').relative_to(PROJECT_ROOT)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
