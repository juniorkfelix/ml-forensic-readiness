def rows(name: str, only_runs: bool = True) -> list[dict]:
    data = list(csv.DictReader((C4 / name).open(encoding="utf-8")))
    return [r for r in data if r["experiment_id"].startswith("EXP")] if only_runs else data


def aggs(name: str) -> list[dict]:
    return [r for r in rows(name, False) if r["experiment_id"].startswith("AGGREGATE")]


def f(v, nd=3, pct=False):
    if v in (None, "", "nan", "None"):
        return "–"
    try:
        x = float(v)
    except ValueError:
        return str(v)
    return f"{x * 100:.{nd}f} %" if pct else f"{x:.{nd}f}"


def table(header: list[str], body: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in body]
    return "\n".join(out)


def mean_sd(vals: list[float], nd=3) -> str:
    vals = [v for v in vals if v is not None]
    if not vals:
        return "–"
    if len(vals) == 1:
        return f"{vals[0]:.{nd}f}"
    return f"{st.mean(vals):.{nd}f} ± {st.stdev(vals):.{nd}f}"


def img(path: str, caption: str) -> str:
    return f"![{caption}]({path})\n\n*{caption}*\n"


